"""Inventory of the real objects your parts fit (things/), and what is still unmeasured.

    ./venv/bin/python scripts/things.py           # inventory + the still-to-measure list
    ./venv/bin/python scripts/things.py --write   # regenerate things/INVENTORY.md
    ./venv/bin/python scripts/things.py --check   # exit 1 if INVENTORY.md is stale (build_all runs this)

A thing is things/<name>.py: its docstring's first line says what it is; each constant's
comment starts with a source tag -- MEASURED, DATASHEET, GIVEN or ASSUMED -- then where the
number came from. CLAUDE.md imports INVENTORY.md, so every session starts knowing what is on
file and what still needs measuring.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THINGS = ROOT / "things"
INVENTORY = THINGS / "INVENTORY.md"
TAGS = ("MEASURED", "DATASHEET", "GIVEN", "ASSUMED")
CONST = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*(.+?)\s*(?:#\s*(.*))?$")


def things() -> list[Path]:
    return sorted(p for p in THINGS.glob("*.py") if p.name != "__init__.py") if THINGS.exists() else []


def values(path: Path) -> list[tuple[str, str, str, str]]:
    """(name, value, tag, note) for each top-level UPPER_CASE constant; tag '' if untagged."""
    out = []
    for line in path.read_text().splitlines():
        m = CONST.match(line)
        if not m:
            continue
        name, value, comment = m.group(1), m.group(2), (m.group(3) or "").strip()
        first = re.split(r"[\s:;,(-]", comment, maxsplit=1)[0].upper() if comment else ""
        tag = first if first in TAGS else ""
        out.append((name, value, tag, comment))
    return out


def users(name: str) -> list[str]:
    pat = re.compile(rf"\bthings\.{name}\b|from things import [^\n]*\b{name}\b")
    hits = set()
    for f in [*ROOT.glob("parts/*/*.py"), *ROOT.glob("assemblies/*/*.py"), *ROOT.glob("common/*.py")]:
        if "templates" not in f.parts and pat.search(f.read_text()):
            hits.add(f.parent.name if f.parent.name not in ("common",) else f"common/{f.name}")
    return sorted(hits)


def summary(path: Path) -> str:
    doc = ast.get_docstring(ast.parse(path.read_text())) or ""
    return doc.strip().splitlines()[0] if doc.strip() else "(no docstring)"


def render() -> str:
    rows, todo, untagged = [], [], []
    for p in things():
        vals = values(p)
        assumed = [v for v in vals if v[2] == "ASSUMED"]
        rows.append(f"| `{p.stem}` | {summary(p)} | {len(vals)} | {len(assumed)} | "
                    f"{', '.join(users(p.stem)) or '--'} |")
        todo += [f"- `{p.stem}.{n}` = {v} -- {c}" for n, v, _, c in assumed]
        untagged += [f"- `{p.stem}.{n}` = {v}" for n, v, t, _ in vals if not t]
    out = ["# Things on file", "",
           "_Generated by `./venv/bin/python scripts/things.py --write` -- don't edit by hand; edit "
           "`things/<name>.py`. Check here before asking the user for a measurement._", ""]
    if rows:
        out += ["| Thing | What | Values | Still ASSUMED | Used by |", "| --- | --- | --- | --- | --- |", *rows]
    else:
        out += ["Nothing yet. When the user gives measurements of something future parts will fit "
                "(a rack, a rail, a board, a wall), record it: `scripts/new.py thing <name>`."]
    if todo:
        out += ["", "## Still to measure", "", *todo]
    if untagged:
        out += ["", "## Missing a source tag (MEASURED / DATASHEET / GIVEN / ASSUMED)", "", *untagged]
    return "\n".join(out) + "\n"


def main() -> int:
    args = sys.argv[1:]
    text = render()
    if args == ["--write"]:
        INVENTORY.write_text(text)
        print(f"wrote {INVENTORY.relative_to(ROOT)}")
        return 0
    if args == ["--check"]:
        if not INVENTORY.exists() and not things():
            return 0  # a fresh copy with nothing recorded yet
        if not INVENTORY.exists() or INVENTORY.read_text() != text:
            print("things/INVENTORY.md is out of date -- run: ./venv/bin/python scripts/things.py --write")
            return 1
        return 0
    if args:
        print(__doc__)
        return 2
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
